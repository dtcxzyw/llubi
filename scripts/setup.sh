#!/usr/bin/env bash
# Build the local toolchain used by the llubi web playground.
#
# The script is intentionally self-contained and idempotent:
#   - installs a pinned Node.js into a cache directory
#   - installs a pinned Emscripten SDK into the same cache directory
#   - writes <tools>/env.sh and, on GitHub Actions, exports PATH entries
#
# Environment knobs:
#   LLUBI_TOOLS_DIR      where downloaded tools live
#                        (default: $XDG_CACHE_HOME/llubi-web or ~/.cache/llubi-web)
#   LLUBI_NODE_VERSION   Node.js version to install (default: 22.14.0)
#   LLUBI_EMSDK_VERSION  Emscripten version to install (default: 6.0.13)
#   LLUBI_EMSDK_REPO     emsdk git URL
#   LLUBI_SETUP_SKIP_EMSDK=1 to skip the Emscripten installation

set -euo pipefail

log() { printf '[setup] %s\n' "$*" >&2; }
die() { printf '[setup] error: %s\n' "$*" >&2; exit 1; }

need() {
  command -v "$1" >/dev/null 2>&1 || die "required command '$1' not found"
}

need git
need tar
need python3
need cmake
need ninja

if ! command -v ccache >/dev/null 2>&1 && [ "${GITHUB_ACTIONS:-}" = "true" ]; then
  log "installing ccache for CI"
  sudo apt-get update -qq
  sudo apt-get install -y -qq ccache
fi

if command -v ccache >/dev/null 2>&1; then
  log "ccache: $(ccache --version | head -n 1)"
else
  log "warning: ccache not found; builds will not use the compiler cache"
fi

TOOLS_DIR="${LLUBI_TOOLS_DIR:-${XDG_CACHE_HOME:-$HOME/.cache}/llubi-web}"
NODE_VERSION="${LLUBI_NODE_VERSION:-22.14.0}"
EMSDK_VERSION="${LLUBI_EMSDK_VERSION:-6.0.13}"
EMSDK_REPO="${LLUBI_EMSDK_REPO:-https://github.com/emscripten-core/emsdk.git}"

mkdir -p "$TOOLS_DIR"

case "$(uname -s)" in
  Linux)  OS=linux ;;
  Darwin) OS=darwin ;;
  *) die "unsupported operating system: $(uname -s)" ;;
esac

case "$(uname -m)" in
  x86_64|amd64) NODE_ARCH=x64 ;;
  arm64|aarch64) NODE_ARCH=arm64 ;;
  *) die "unsupported architecture: $(uname -m)" ;;
esac

install_node() {
  local name="node-v${NODE_VERSION}-${OS}-${NODE_ARCH}"
  local dest="$TOOLS_DIR/$name"
  local tarball="$TOOLS_DIR/$name.tar.xz"

  if [ -x "$dest/bin/node" ]; then
    log "Node.js $NODE_VERSION already installed"
  else
    local url="https://nodejs.org/dist/v${NODE_VERSION}/${name}.tar.xz"
    log "downloading $url"
    if command -v curl >/dev/null 2>&1; then
      curl -fL --retry 3 --retry-delay 2 -o "$tarball" "$url"
    else
      wget -q -O "$tarball" "$url"
    fi
    tar -xJf "$tarball" -C "$TOOLS_DIR"
    rm -f "$tarball"
    [ -x "$dest/bin/node" ] || die "failed to install Node.js"
  fi

  ln -sfn "$dest" "$TOOLS_DIR/node"
  export PATH="$TOOLS_DIR/node/bin:$PATH"
}

install_emsdk() {
  local dir="$TOOLS_DIR/emsdk"
  local marker="$dir/.llubi-emsdk-version"

  if [ ! -d "$dir/.git" ]; then
    log "cloning emsdk"
    git clone --depth 1 "$EMSDK_REPO" "$dir"
  fi

  if [ ! -f "$marker" ] || [ "$(cat "$marker")" != "$EMSDK_VERSION" ]; then
    log "installing Emscripten $EMSDK_VERSION (this may take a while)"
    (
      cd "$dir"
      ./emsdk install "$EMSDK_VERSION"
      ./emsdk activate "$EMSDK_VERSION"
      printf '%s\n' "$EMSDK_VERSION" > "$marker"
    )
  else
    log "Emscripten $EMSDK_VERSION already installed"
  fi

  # shellcheck disable=SC1091
  source "$dir/emsdk_env.sh" >/dev/null 2>&1
}

install_node
if [ "${LLUBI_SETUP_SKIP_EMSDK:-0}" != "1" ]; then
  install_emsdk
fi

NODE_BIN="$TOOLS_DIR/node/bin"
ENV_FILE="$TOOLS_DIR/env.sh"
{
  printf '# Generated by scripts/setup.sh\n'
  printf 'export LLUBI_TOOLS_DIR=%q\n' "$TOOLS_DIR"
  printf 'export PATH=%q:"$PATH"\n' "$NODE_BIN"
  if [ "${LLUBI_SETUP_SKIP_EMSDK:-0}" != "1" ]; then
    printf 'if [ -f %q ]; then\n' "$TOOLS_DIR/emsdk/emsdk_env.sh"
    printf '  . %q >/dev/null 2>&1\n' "$TOOLS_DIR/emsdk/emsdk_env.sh"
    printf 'fi\n'
  fi
} > "$ENV_FILE"

if [ -n "${GITHUB_PATH:-}" ]; then
  printf '%s\n' "$NODE_BIN" >> "$GITHUB_PATH"
  if [ "${LLUBI_SETUP_SKIP_EMSDK:-0}" != "1" ]; then
    for tool in emcc em++ emar emranlib; do
      tool_path="$(command -v "$tool" 2>/dev/null || true)"
      if [ -n "$tool_path" ]; then
        printf '%s\n' "$(dirname "$tool_path")" >> "$GITHUB_PATH"
        break
      fi
    done
  fi
fi

log "node: $(command -v node) ($(node --version))"
if [ "${LLUBI_SETUP_SKIP_EMSDK:-0}" != "1" ]; then
  log "emcc: $(command -v emcc) ($(emcc --version | head -n 1))"
fi
log "environment file: $ENV_FILE"
log "run 'source $ENV_FILE' in your shell, or use scripts/dev.py"
