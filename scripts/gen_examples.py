#!/usr/bin/env python3
"""Collect llubi lit tests into a JSON example catalog for the playground."""

from __future__ import annotations

import argparse
import json
import math
import re
import shlex
import sys
from pathlib import Path

RUN_RE = re.compile(r"^\s*;\s*RUN:\s*(.+?)\s*$", re.M)
NOTE_RE = re.compile(
    r"^\s*;\s*NOTE:\s*Assertions have been autogenerated by "
    r"utils/update_llubi_test_checks\.py.*$"
)
CHECK_RE = re.compile(r"^\s*;\s*([A-Z][A-Z0-9_-]*)(?:-[A-Z]+)?:\s")

VALUE_FLAGS = {
    "--entry-function": "entryFunction",
    "--fake-argv0": "fakeArgv0",
    "--max-mem": "maxMem",
    "--max-steps": "maxSteps",
    "--max-stack-depth": "maxStackDepth",
    "--vscale": "vscale",
    "--seed": "seed",
    "--undef-behavior": "undefBehavior",
    "--nan-behavior": "nanBehavior",
}
BOOL_FLAGS = {
    "--deterministic": ("deterministic", True),
    "--disable-verify": ("disableVerify", True),
}
NAN_VALUES = {"nondet", "preferred", "quieting", "unchanged", "target-specific"}
UNDEF_VALUES = {"nondet", "zero"}


def fail(message: str) -> None:
    print(f"[examples] error: {message}", file=sys.stderr)
    raise SystemExit(1)


def strip_test_directives(text: str) -> str:
    lines = []
    for line in text.splitlines():
        if NOTE_RE.match(line):
            continue
        match = CHECK_RE.match(line)
        if match and match.group(1) not in {"RUN", "NOTE"}:
            continue
        lines.append(line)
    return "\n".join(lines).rstrip() + "\n"


def parse_run_options(text: str) -> dict[str, object]:
    match = RUN_RE.search(text)
    if not match:
        return {}
    command = match.group(1)
    direct = re.match(r"^\s*(?:not\s+)?llubi\b(.*)$", command)
    if not direct:
        return {}
    args_text = re.split(r"\s*(?:<|2>|\|)", direct.group(1), maxsplit=1)[0]
    try:
        args = shlex.split(args_text)
    except ValueError:
        return {}

    options: dict[str, object] = {}
    index = 0
    while index < len(args):
        arg = args[index]
        if arg == "--verbose":
            index += 1
            continue
        if arg == "--":
            options["argv"] = args[index + 1 :]
            break
        if arg in BOOL_FLAGS:
            key, value = BOOL_FLAGS[arg]
            options[key] = value
            index += 1
            continue
        if arg == "--fuse-fmuladd=false" or arg == "--fuse-fmuladd=true":
            options["fuseFMulAdd"] = arg.endswith("true")
            index += 1
            continue
        matched_value = None
        for flag, key in VALUE_FLAGS.items():
            if arg == flag:
                if index + 1 >= len(args):
                    return {}
                matched_value = (key, args[index + 1])
                index += 2
                break
            if arg.startswith(flag + "="):
                matched_value = (key, arg[len(flag) + 1 :])
                index += 1
                break
        if matched_value is None:
            return {}
        key, value = matched_value
        try:
            if key == "maxMem":
                bytes_value = int(value, 10)
                if bytes_value < 0:
                    return {}
                options["maxMemMiB"] = max(1, math.ceil(bytes_value / (1024 * 1024)))
            elif key in {"maxSteps", "maxStackDepth", "vscale", "seed"}:
                options[key] = int(value, 10)
            elif key == "nanBehavior":
                if value not in NAN_VALUES:
                    return {}
                options[key] = value
            elif key == "undefBehavior":
                if value not in UNDEF_VALUES:
                    return {}
                options[key] = value
            else:
                options[key] = value
        except ValueError:
            return {}
    return options


def collect(llvm_source: Path) -> list[dict[str, object]]:
    tests = llvm_source / "llvm" / "test" / "tools" / "llubi"
    if not tests.is_dir():
        fail(f"missing llubi tests directory: {tests}")
    examples = []
    for path in sorted(tests.rglob("*.ll")):
        text = path.read_text(encoding="utf-8", errors="replace")
        name = path.relative_to(tests).with_suffix("").as_posix()
        run_match = RUN_RE.search(text)
        examples.append(
            {
                "name": name,
                "ir": strip_test_directives(text),
                "options": parse_run_options(text),
                "run": run_match.group(1) if run_match else "",
            }
        )
    return examples


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--llvm-source", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    llvm_source = Path(args.llvm_source).expanduser().resolve()
    output = Path(args.output).expanduser().resolve()
    examples = collect(llvm_source)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        json.dumps({"examples": examples}, indent=2) + "\n", encoding="utf-8"
    )
    print(f"[examples] collected {len(examples)} tests -> {output}", flush=True)


if __name__ == "__main__":
    main()
